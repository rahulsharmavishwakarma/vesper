import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function readmeBannerSource(artwork, tokens) {
  const source = artwork.match(/^<svg\b[^>]*viewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>\s*$/);
  if (!source) throw new Error('Expected the canonical Vesper SVG with a viewBox.');
  const palette = ['--color-bg', '--color-ink', '--color-accent'].map((name) => {
    const value = tokens.match(new RegExp(`${name}:\\s*([^;]+);`))?.[1];
    if (!value) throw new Error(`Missing brand token: ${name}`);
    return `      ${name}: ${value};`;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="320" viewBox="0 0 1200 320" role="img" aria-labelledby="title description">
  <!-- Hallmark · component: static banner · genre: atmospheric · theme: existing Vesper Studio
       audience: users and contributors · use: get started from source · tone: quiet
       states: static artwork; no interactive states or motion
       contrast: pass (40–41) · honest: pass (46) · chrome: pass (47) · tokens: pass (48)
       Hallmark · pre-emit critique: P5 H4 E5 S5 R5 V4 -->
  <!-- Generated by scripts/generate-readme-banner.mjs; edit the canonical artwork/tokens, not this derivative. -->
  <title id="title">Vesper</title>
  <desc id="description">The original Songbird and complete Vesper wordmark on graphite.</desc>
  <style>
    :root {
${palette.join('\n')}
    }
    .background { fill: var(--color-bg); }
    .vesper-mark { color: var(--color-accent); }
    .vesper-wordmark { color: var(--color-ink); }
  </style>
  <rect class="background" width="1200" height="320" rx="24"/>
  <svg x="240" y="64" width="720" height="192" viewBox="${source[1]}">
${source[2].trimEnd()}
  </svg>
</svg>
`;
}

export function generateReadmeBanner({ check = false } = {}) {
  const read = (path) => readFileSync(resolve(root, path), 'utf8');
  const output = resolve(root, 'docs/assets/vesper-banner.svg');
  const banner = readmeBannerSource(
    read('apps/desktop/src/assets/vesper.svg'),
    read('apps/desktop/src/tokens.css'),
  );
  if (check) {
    if (readFileSync(output, 'utf8') !== banner) {
      throw new Error('README banner is stale. Run node scripts/generate-readme-banner.mjs.');
    }
    console.log('README banner matches the canonical Vesper artwork and tokens.');
  } else {
    mkdirSync(dirname(output), { recursive: true });
    writeFileSync(output, banner);
    console.log('Generated docs/assets/vesper-banner.svg.');
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  generateReadmeBanner({ check: process.argv.includes('--check') });
}
