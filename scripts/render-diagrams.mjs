#!/usr/bin/env node
// Render docs/diagrams/*.mmd to light and dark SVGs styled with the app's design
// tokens (apps/desktop/src/tokens.css) and the Bricolage Grotesque UI font.
// Usage: node scripts/render-diagrams.mjs [name ...]
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const SOURCES = join(root, 'docs/diagrams');
export const OUTPUT = join(root, 'docs/assets/diagrams');
export const TOKENS = join(root, 'apps/desktop/src/tokens.css');
const FONT = join(root, 'apps/desktop/src/assets/bricolage-grotesque.ttf');
const CACHE = join(root, '.cache/diagrams');
const MERMAID_CLI = '@mermaid-js/mermaid-cli@11.4.2';
const FONTTOOLS = 'fonttools[woff]==4.60.1';
// One static instance at the UI's text weight, Latin plus the punctuation and
// arrows the diagrams use, keeps the embedded font near 12 KB per SVG.
const FONT_INSTANCE = ['wght=450', 'wdth=100', 'opsz=14'];
const FONT_UNICODES =
  'U+0020-007E,U+00A0,U+00B7,U+00D7,U+2013,U+2014,U+2019,U+201C,U+201D,U+2026,U+2190-2194';

const FONT_FAMILY =
  "'Bricolage Grotesque', -apple-system, 'Segoe UI', Helvetica, Arial, sans-serif";

export const sha256 = (text) => createHash('sha256').update(text).digest('hex');

// Merges every block for a selector, in file order, as the cascade does.
export function readTokens(css) {
  const blocks = (selector) => {
    const tokens = {};
    for (let start = css.indexOf(selector); start >= 0; start = css.indexOf(selector, start + 1)) {
      const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('}', start));
      for (const [, name, value] of body.matchAll(/--color-([a-z-]+):\s*([^;]+);/g)) {
        tokens[name] = value.trim();
      }
    }
    if (!Object.keys(tokens).length) throw new Error(`Missing ${selector} in tokens.css`);
    return tokens;
  };
  const dark = blocks(':root {');
  return { dark, light: { ...dark, ...blocks(":root[data-theme='light'] {") } };
}

export function themeFor(t) {
  return {
    background: t.bg,
    fontFamily: FONT_FAMILY,
    fontSize: '15px',
    primaryColor: t.raised,
    primaryBorderColor: t['control-edge'],
    primaryTextColor: t.ink,
    secondaryColor: t.tint,
    secondaryBorderColor: t.accent,
    secondaryTextColor: t.ink,
    tertiaryColor: t.panel,
    tertiaryBorderColor: t.line,
    tertiaryTextColor: t.ink,
    lineColor: t.muted,
    textColor: t.ink,
    titleColor: t.accent,
    clusterBkg: t.panel,
    clusterBorder: t.line,
    edgeLabelBackground: t.bg,
    actorBkg: t.raised,
    actorBorder: t['control-edge'],
    actorTextColor: t.ink,
    actorLineColor: t.line,
    signalColor: t.muted,
    signalTextColor: t.ink,
    labelBoxBkgColor: t.raised,
    labelBoxBorderColor: t['control-edge'],
    labelTextColor: t.ink,
    loopTextColor: t.ink,
    noteBkgColor: t.tint,
    noteTextColor: t.ink,
    noteBorderColor: t.accent,
    activationBkgColor: t.tint,
    activationBorderColor: t.accent,
    sequenceNumberColor: t['on-accent'],
  };
}

export function header(name, source, tokens) {
  return `<!-- Generated by scripts/render-diagrams.mjs from docs/diagrams/${name}.mmd; do not edit. source-sha256=${sha256(source)} tokens-sha256=${sha256(tokens)} -->\n`;
}

function fontFace() {
  const woff2 = join(CACHE, 'bricolage-450.woff2');
  if (!existsSync(woff2)) {
    const instance = join(CACHE, 'bricolage-450.ttf');
    const uvx = (...args) =>
      execFileSync('uvx', ['-q', '--from', FONTTOOLS, ...args], { stdio: 'inherit' });
    uvx('fonttools', 'varLib.instancer', FONT, ...FONT_INSTANCE, '-q', '-o', instance);
    uvx(
      'pyftsubset',
      instance,
      `--unicodes=${FONT_UNICODES}`,
      '--flavor=woff2',
      '--layout-features=kern,liga',
      `--output-file=${woff2}`,
    );
  }
  const data = readFileSync(woff2).toString('base64');
  return `@font-face { font-family: 'Bricolage Grotesque'; font-weight: 450; src: url(data:font/woff2;base64,${data}) format('woff2'); }`;
}

async function chromiumPath() {
  const { chromium } = await import('@playwright/test');
  const path = chromium.executablePath();
  if (!existsSync(path)) throw new Error('Chromium is missing; run `make setup-checks` first.');
  return path;
}

async function main(names) {
  mkdirSync(CACHE, { recursive: true });
  mkdirSync(OUTPUT, { recursive: true });
  const tokensCss = readFileSync(TOKENS, 'utf8');
  const tokens = readTokens(tokensCss);
  const css = join(CACHE, 'diagram.css');
  writeFileSync(
    css,
    `${fontFace()}
svg { font-weight: 450; }
.node rect, .node .basic.label-container { rx: 10px; ry: 10px; }
.cluster rect { rx: 16px; ry: 16px; }
.cluster-label, .cluster-label span { font-weight: 450; letter-spacing: 0.01em; }
.edgeLabel rect { opacity: 1; }
`,
  );
  const browser = join(CACHE, 'puppeteer.json');
  writeFileSync(
    browser,
    JSON.stringify({ executablePath: await chromiumPath(), args: ['--no-sandbox'] }),
  );
  const sources = readdirSync(SOURCES)
    .filter((file) => file.endsWith('.mmd'))
    .map((file) => basename(file, '.mmd'))
    .filter((name) => !names.length || names.includes(name));
  for (const name of sources) {
    const input = join(SOURCES, `${name}.mmd`);
    const source = readFileSync(input, 'utf8');
    for (const mode of ['light', 'dark']) {
      const config = join(CACHE, `${mode}.json`);
      writeFileSync(
        config,
        JSON.stringify({
          theme: 'base',
          htmlLabels: false,
          themeVariables: themeFor(tokens[mode]),
          flowchart: {
            htmlLabels: false,
            curve: 'basis',
            padding: 14,
            nodeSpacing: 40,
            rankSpacing: 48,
          },
          sequence: {
            mirrorActors: false,
            actorMargin: 48,
            actorFontFamily: FONT_FAMILY,
            noteFontFamily: FONT_FAMILY,
            messageFontFamily: FONT_FAMILY,
          },
        }),
      );
      const output = join(OUTPUT, `${name}.${mode}.svg`);
      execFileSync(
        'npx',
        [
          '--yes',
          MERMAID_CLI,
          '-q',
          '-i',
          input,
          '-o',
          output,
          '-c',
          config,
          '-C',
          css,
          '-p',
          browser,
          '-b',
          tokens[mode].bg,
        ],
        { stdio: 'inherit' },
      );
      const svg = readFileSync(output, 'utf8').trimEnd();
      writeFileSync(output, `${header(name, source, tokensCss)}${svg}\n`);
    }
    console.log(`Rendered ${name}`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main(process.argv.slice(2));
